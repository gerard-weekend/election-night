// Build index.html from the designer's three pages in docs/design/.
//
//   node tools/build-index.mjs
//
// The brief says "the design is final, do not restyle", so the markup is taken
// verbatim rather than retyped: each page's <main class="stage"> and its own
// <style> block are lifted as they are. Only three things change — all three
// stages go in one document, the ticker is hoisted out of the per-view markup
// so it never moves between views, and sample ticker calls are dropped.
//
// Re-run this if the designer sends a new bundle. Do not hand-edit index.html.

import { readFile, writeFile } from 'node:fs/promises'

// Rotation order; also the DOM order of the stages.
const VIEWS = ['house', 'senate', 'governors', 'california']
const DIR = 'docs/design'

const between = (s, start, end, from = 0) => {
  const a = s.indexOf(start, from)
  if (a < 0) return null
  const b = s.indexOf(end, a)
  return b < 0 ? null : { text: s.slice(a, b + end.length), start: a, end: b + end.length }
}

/**
 * Scope one page's CSS to its own stage.
 *
 * Each design page carries its own <style> block, and several of them define
 * the same class with different values — .tile is 46 px on the Senate and
 * 58 px on Governors, .legend is a column on one and a row on the other.
 * Concatenating them into one document let the last page win and broke the
 * others, which put the Governors legend on top of its map. Prefixing every
 * selector with the owning stage keeps each page's rules to itself.
 */
function scope (css, view) {
  const prefix = `.stage[data-view="${view}"]`
  return css.replace(/(^|\})([^{}@]+)\{/g, (m, close, selectors) => {
    const scoped = selectors
      .split(',')
      .map(sel => {
        const t = sel.trim()
        if (!t || t.startsWith('@')) return sel
        // A rule on the stage itself must not become a descendant selector.
        if (t.startsWith('.stage')) return t
        return `${prefix} ${t}`
      })
      .join(', ')
    return `${close}${selectors.startsWith('\n') ? '\n' : ''}${scoped} {`
  })
}

const stages = []
const styles = []
let ticker = null

for (const view of VIEWS) {
  const html = await readFile(`${DIR}/${view}.html`, 'utf8')

  const style = between(html, '<style>', '</style>')
  if (style) {
    styles.push(`/* ---- ${view} ---- */\n` + scope(style.text.replace(/<\/?style>/g, '').trim(), view))
  }

  const stage = between(html, '<main class="stage"', '</main>')
  if (!stage) throw new Error(`no .stage found in ${view}.html`)
  let markup = stage.text

  // The ticker is identical on all three pages and must not move or re-render
  // between views, so hoist one copy out of the stages.
  const tk = between(markup, '<footer class="tk"', '</footer>')
  if (tk) {
    if (!ticker) ticker = tk.text
    markup = markup.slice(0, tk.start) + markup.slice(tk.end)
  }
  stages.push(markup.trimEnd())
}

if (!ticker) throw new Error('no ticker found in any design page')

// Keep one call as the pattern to clone; drop the rest of the sample set.
ticker = ticker.replace(
  /(<div class="tk-calls"[^>]*>)([\s\S]*?)(<\/div>)/,
  (_, open, inner, close) => {
    const first = inner.match(/<span data-template="shell\.call"[\s\S]*?<\/span>\s*(?=<span data-template|$)/)
    return open + '\n    ' + (first ? first[0].trim() : '') + '\n  ' + close
  },
)

const out = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Election Night 2026</title>
<link rel="icon" href="data:,">
<meta name="viewport" content="width=device-width,initial-scale=1">
<!--
  GENERATED by tools/build-index.mjs from docs/design/. Do not hand-edit:
  re-run the generator instead, so a new design bundle can be dropped in.

  All three stages live here at once and cross-fade; the ticker sits outside
  them so it never moves. Data is wired in by src/main.js.
-->
<link rel="stylesheet" href="assets/tokens.css">
<link rel="stylesheet" href="assets/shell.css">
<style>
${styles.join('\n\n')}
</style>
</head>
<body>
${stages.join('\n\n')}

<!-- The ticker sits outside the stages so it never moves or re-renders
     between views. .tk-fixed reproduces the stage's scaled 1920x1080 box,
     because .tk is positioned against it. -->
<div class="tk-fixed">
${ticker}
</div>

<script src="assets/fit.js"></script>
<script type="module" src="src/main.js"></script>
</body>
</html>
`

await writeFile('index.html', out)
console.log(`index.html written: ${VIEWS.length} stages, ${styles.length} style blocks, ticker hoisted`)
